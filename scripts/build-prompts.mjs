// Build prompts/index.js — inline every prompt version as a JS module the
// middleware can relatively import (the gateway's moejs engine allows only
// relative imports inside the package directory; no fs, no fetch).
//   node scripts/build-prompts.mjs
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = dirname(dirname(fileURLToPath(import.meta.url)))

const versions = [
  { id: "v52",      label: "完整版 v5.2", badge: "默认", desc: "吸收重写终版：工作台契约 + 红蓝蓝图 + 卡密专项 + 交付纪律", file: "assets/hangong-prompt.md" },
  { id: "v5",       label: "轻量 V5",     badge: "",     desc: "v5 精简规范：工程原则 + 完整工作规范", file: "prompts/v5.md" },
  { id: "v4",       label: "轻量 V4",     badge: "",     desc: "v4 精简规范 + 旧版激活词握手", file: "prompts/v4.md" },
  { id: "v3",       label: "轻量 V3",     badge: "",     desc: "寒霜工作规范 v3：最短可用版", file: "prompts/v3.md" },
  { id: "variantb", label: "英文变体 B",  badge: "EN",   desc: "English variant: authorized-environment spec", file: "prompts/variantb.md" },
]

const out = []
out.push(`// generated by scripts/build-prompts.mjs — do not edit by hand
// edit prompts/*.md (or assets/hangong-prompt.md), then rebuild.
export const DEFAULT_VERSION = "v52"

export const VERSIONS = {
`)
let total = 0
for (const v of versions) {
  const text = readFileSync(join(root, v.file), "utf8")
  total += text.length
  out.push(`  ${JSON.stringify(v.id)}: {\n    label: ${JSON.stringify(v.label)},\n    badge: ${JSON.stringify(v.badge)},\n    desc: ${JSON.stringify(v.desc)},\n    chars: ${text.length},\n    text: ${JSON.stringify(text)},\n  },\n`)
}
out.push(`}\n`)
writeFileSync(join(root, "prompts/index.js"), out.join(""))
console.log("prompts/index.js built:", versions.length, "versions,", total, "chars total")
